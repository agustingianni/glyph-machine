def social_tags(title, desc, path):
    """Tags that give a search result or a shared link its title, text, and
    preview image. `path` is the page's folder in the site, such as "life/".
    The canonical link names the one address to list, since GitHub Pages also
    serves each page at <folder>/index.html."""
    url = SITE_URL + path
    title, desc = html.escape(title), html.escape(desc)
    return f"""    <meta name="description" content="{desc}" />
    <link rel="canonical" href="{url}" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="{SITE_NAME}" />
    <meta property="og:title" content="{title}" />
    <meta property="og:description" content="{desc}" />
    <meta property="og:url" content="{url}" />
    <meta property="og:image" content="{url}preview.png" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta name="twitter:card" content="summary_large_image" />"""

