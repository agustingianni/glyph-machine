def font_face(family, file, indent="      "):
    return (f'{indent}@font-face {{\n'
            f'{indent}  font-family: {family};\n'
            f'{indent}  src: url(../fonts/{file}) format("woff2");\n'
            f'{indent}}}')

def keyframes(name, tag, lo, hi, indent="      "):
    return (f'{indent}@keyframes {name} {{\n'
            f'{indent}  from {{ font-variation-settings: "{tag}" {lo}; }}\n'
            f'{indent}  to {{ font-variation-settings: "{tag}" {hi}; }}\n'
            f'{indent}}}')

def spans(text, stagger):
    # One span per character, each a little further along the loop.
    return "".join(f'<span style="animation-delay: {-i * stagger:g}s">{c}</span>'
                   for i, c in enumerate(text))

def legend(chips):
    items = "\n".join(f'        <span class="chip">{c}</span>' for c in chips)
    return f'      <div class="legend">\n{items}\n      </div>'

