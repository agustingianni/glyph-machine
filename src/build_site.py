def axis_page(cfg):
    tag, lo, hi, loop = cfg["tag"], cfg["min"], cfg["max"], cfg["loop"]
    label = cfg["label"]
    extra = f"\n        {cfg['stage_css']}" if "stage_css" in cfg else ""
    head = f"""{font_face("Demo", cfg["file"])}
{keyframes("drive", tag, lo, hi)}
      .stage {{
        font-family: Demo;
        font-size: {cfg['size']};
        font-variation-settings: "{tag}" {lo};
        color: {cfg.get('color', '#fff')};
        animation: drive {loop}s linear infinite;{extra}
      }}
      .word {{ font-family: Demo; font-size: min(15vmin, 96px); }}
      .word span {{ animation: drive {loop}s linear infinite; }}"""

    word_html = ""
    if cfg.get("word"):
        word_html = f"""
      <div class="controls">
        <input type="text" id="word" value="{cfg['word']}" maxlength="14"
          aria-label="your word" autocomplete="off" spellcheck="false" />
      </div>
      <div class="word" id="wordout" aria-hidden="true"></div>"""

    body = f"""      <h1 class="title">{cfg['title']}</h1>
      <p class="lede">{cfg['lede']}</p>

      <div class="stage" id="stage" aria-hidden="true">{cfg['char']}</div>

      <div class="controls">
        <button id="toggle">Pause</button>
        <input type="range" id="scrub" min="{lo}" max="{hi}" value="{lo}"
          aria-label="{label} axis" />
        <span class="readout" id="readout">{label}: auto</span>
      </div>{word_html}

{legend(cfg['chips'])}

      <p class="foot">{cfg['foot']}</p>"""

    script = f"""    <script>
      var LO = {lo}, HI = {hi}, LOOP = {loop}, STAGGER = 0.12;
      var stage = document.getElementById("stage"),
        toggle = document.getElementById("toggle"),
        scrub = document.getElementById("scrub"),
        readout = document.getElementById("readout"),
        word = document.getElementById("word"),
        wordout = document.getElementById("wordout");
      var playing = !matchMedia("(prefers-reduced-motion: reduce)").matches;

      // The stage and each letter of the word run the CSS animation "drive",
      // which sweeps the axis once every LOOP seconds. Pause and the slider
      // set the same clock on all of them. Each letter has a negative
      // animation-delay, so it runs STAGGER seconds ahead of the one before it
      // and the word ripples.
      function now() {{
        return stage.getAnimations()[0].currentTime;
      }}
      function setClock(ms) {{
        // Pause or play first: either one finishes on the next frame, and
        // would move a time that was set before it.
        document.getAnimations().forEach(function (a) {{
          playing ? a.play() : a.pause();
          a.currentTime = ms;
        }});
        var value = Math.round(LO + (ms / 1000 / LOOP % 1) * (HI - LO));
        toggle.textContent = playing ? "Pause" : "Play";
        readout.textContent = "{label}: " + (playing ? "auto" : value);
      }}
      toggle.onclick = function () {{
        playing = !playing;
        setClock(now());
      }};
      scrub.oninput = function () {{
        playing = false;
        setClock((scrub.value - LO) / (HI - LO) * LOOP * 1000);
      }};
      if (word) {{
        word.addEventListener("input", function () {{
          wordout.textContent = "";
          Array.from(word.value || " ").forEach(function (ch, i) {{
            var s = document.createElement("span");
            s.textContent = ch === " " ? "\\u00a0" : ch;
            s.style.animationDelay = -(i + 1) * STAGGER + "s";
            wordout.appendChild(s);
          }});
          setClock(now());
        }});
        word.dispatchEvent(new Event("input"));
      }}
      setClock(0);
    </script>"""
    return shell(cfg, head, body, script)

