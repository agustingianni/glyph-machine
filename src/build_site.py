# -------------------------------------------------------------------- hash page
HASH_PRESETS = [("Empty", ""), ("abc", "abc"), ("hello", "hello"),
                ("Quick brown fox", "The quick brown fox jumps over the lazy dog"),
                ("55 characters", "a" * 55)]

# Shared by the page and its preview. Firefox runs the Graphite font and Safari
# runs the AAT one. Each font wants a few invisible characters around the
# message: they give even an empty message a run of text to shape, and the
# AAT font needs four more to have room to grow the run. A browser that does
# not run the font draws nothing, so a probe checks for the 32 digits (0.6em
# each, 19.2em in all) before the page shows anything.
HASH_SETUP = """      var GRAPHITE = CSS.supports("font-tech(features-graphite)");
      var FAMILY = GRAPHITE ? "MD5Graphite" : "MD5Safari";
      var START = "\\ue000" + (GRAPHITE ? "" : "\\ue002\\ue002\\ue002\\ue002"), END = "\\ue001";
      function whenRunning(yes, no) {
        document.fonts.load("100px " + FAMILY).then(function () {
          var probe = document.createElement("span");
          probe.style.cssText = "position: absolute; visibility: hidden; white-space: pre; font: 100px " + FAMILY;
          probe.textContent = START + "a" + END;
          document.body.appendChild(probe);
          var width = probe.getBoundingClientRect().width;
          probe.remove();
          Math.abs(width - 1920) < 2 ? yes() : no();
        }, no);
      }"""

def hash_fonts(cfg, indent="      "):
    return (font_face("MD5Graphite", cfg["graphite_file"], indent) + "\n"
            + font_face("MD5Safari", cfg["aat_file"], indent))

